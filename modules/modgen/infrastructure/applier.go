const (
	// defaultGoPath is the Go toolchain binary name resolved through PATH
	// when the operator does not set GO_PATH.
	defaultGoPath = "go"
	// defaultApplyTimeout bounds the whole apply verification end to end:
	// module tests in both workspaces plus the custom-binary build.
	defaultApplyTimeout = 10 * time.Minute
	// maxVerifyOutputBytes caps how much tool output an apply step carries:
	// the tail that usually names the broken file and line.
	maxVerifyOutputBytes = 8 << 10
	// customEditionDir is the machine-owned edition package every apply
	// regenerates wholesale from the applied registry.
	customEditionDir = "internal/editions/custom"
	// customMainDir is the machine-owned thin main built on first apply.
	customMainDir = "cmd/lesstruct-custom"
	// appliedRegistryFile is the machine-owned registry of truth listing
	// every applied module.
	appliedRegistryFile = "internal/editions/custom/applied.json"
	// generatedMarker heads every machine-owned file: its presence proves
	// the path is ours to regenerate; its absence refuses the apply.
	generatedMarker = "// Code generated by modgen apply; DO NOT EDIT."
	// goWorkAnchor is the workspace block apply edits textually. The
	// release process maintains intra-workspace requires, so apply never
	// runs go work sync/use — it inserts one use line instead.
	goWorkAnchor = "use ("
	// makeSubmodulesAnchor is the Makefile line apply extends textually.
	makeSubmodulesAnchor = "SUBMODULES :="
	// lesionRootModule is the go.mod module path proving a checkout root.
	lesionRootModule = "module github.com/aristorinjuang/lesstruct"
)

// applyRunFunc executes a command in dir with env and returns its combined
// output. It is the seam unit tests stub to avoid shelling out to real
// toolchains; the env parameter lets tests assert the sandbox.
type applyRunFunc func(ctx context.Context, dir string, env []string, name string, args ...string) ([]byte, error)

// defaultApplyRun shells out to the named binary with a curated,
// network-capable environment: verification must fetch the pinned kernel
// tag for the isolated workspace check, so GOPROXY stays inherited (unlike
// the offline plugin builder). Secrets never travel: only the listed keys
// pass through.
func defaultApplyRun(ctx context.Context, dir string, env []string, name string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Dir = dir
	cmd.Env = env
	return cmd.CombinedOutput()
}

// applyEnv assembles the verification subprocess environment.
func applyEnv(extra []string) []string {
	env := append([]string{}, extra...)
	for _, key := range []string{"PATH", "HOME", "TMPDIR", "GOCACHE", "GOPATH", "GOMODCACHE", "GOPROXY", "GOSUMDB", "GOTOOLCHAIN", "GOFLAGS"} {
		if value := os.Getenv(key); value != "" {
			env = append(env, key+"="+value)
		}
	}
	return env
}

// verifyOutputTail keeps the failure-signaling tail of tool output.
func verifyOutputTail(output []byte) string {
	trimmed := strings.TrimSpace(string(output))
	if len(trimmed) > maxVerifyOutputBytes {
		trimmed = trimmed[len(trimmed)-maxVerifyOutputBytes:]
	}
	return trimmed
}

// applySnapshot holds original shared-file bytes for rollback: every write
// after a failure restores these and removes created paths. Created paths
// only ever name directories this apply created — pre-existing machine
// output is never in the removal set.
type applySnapshot struct {
	files map[string][]byte
	dirs  []string
}

// CheckoutApplier implements modgendomain.Applier by staging generated
// projects into a Lesstruct source checkout: the module tree, the
// machine-writable registry edits, the regenerated custom edition, and a
// compile-and-test verification. Refusals (not a checkout, collisions,
// dirty shared files, hand-owned machine paths) return sentinel errors
// before any write; verification failures keep the applied tree and report
// per-step outcomes.
type CheckoutApplier struct {
	root          string
	goPath        string
	kernelVersion string
	timeout       time.Duration
	run           applyRunFunc
}

func (a *CheckoutApplier) goPathOrDefault() string {
	if a.goPath != "" {
		return a.goPath
	}
	return defaultGoPath
}

func (a *CheckoutApplier) timeoutOrDefault() time.Duration {
	if a.timeout > 0 {
		return a.timeout
	}
	return defaultApplyTimeout
}

func (a *CheckoutApplier) runOrDefault() applyRunFunc {
	if a.run != nil {
		return a.run
	}
	return defaultApplyRun
}

// checkoutRoot resolves the apply root to an absolute directory.
func (a *CheckoutApplier) checkoutRoot() (string, error) {
	root := strings.TrimSpace(a.root)
	if root == "" {
		root = "."
	}
	abs, err := filepath.Abs(root)
	if err != nil {
		return "", fmt.Errorf("%w: %v", modgendomain.ErrNotCheckout, err)
	}
	return abs, nil
}

// IsCheckoutDir reports whether root is a Lesstruct source checkout: the
// root go.mod declares the Lesstruct module and a .git entry exists. The
// edition uses it for the apply readiness flag; Apply itself fails closed
// with ErrNotCheckout.
func IsCheckoutDir(root string) bool {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return false
	}
	first, _, _ := strings.Cut(string(data), "\n")
	if strings.TrimSpace(first) != lesionRootModule {
		return false
	}
	_, err = os.Stat(filepath.Join(root, ".git"))
	return err == nil
}

// checkCheckout proves root is a Lesstruct source checkout: the root go.mod
// declares the Lesstruct module and a .git entry exists. Binary deployments
// fail here with ErrNotCheckout.
func (a *CheckoutApplier) checkCheckout(root string) error {
	if !IsCheckoutDir(root) {
		return modgendomain.ErrNotCheckout
	}
	return nil
}

// checkClean proves the shared registry files carry no uncommitted operator
// changes: git status output for exactly those paths must be empty. The
// run seam executes git so tests never shell out.
func (a *CheckoutApplier) checkClean(ctx context.Context, root string) error {
	run := a.runOrDefault()
	output, err := run(ctx, root, applyEnv(nil), "git", "status", "--porcelain", "--", "go.work", "Makefile")
	if err != nil {
		return fmt.Errorf("%w: cannot inspect tree: %v", modgendomain.ErrTreeDirty, err)
	}
	if strings.TrimSpace(string(output)) != "" {
		return modgendomain.ErrTreeDirty
	}
	return nil
}

// readRegistry reads the machine-owned applied registry. A missing file
// reads as empty; a corrupt file fails closed so a half-written registry
// never silently drops a wired module.
func (a *CheckoutApplier) readRegistry(root string) ([]string, error) {
	data, err := os.ReadFile(filepath.Join(root, appliedRegistryFile))
	if err != nil {
		if os.IsNotExist(err) {
			return []string{}, nil
		}
		return nil, fmt.Errorf("failed to read applied registry: %w", err)
	}
	var modules []string
	if err := json.Unmarshal(data, &modules); err != nil {
		return nil, fmt.Errorf("%w: applied registry is corrupt", modgendomain.ErrTreeDirty)
	}
	return modules, nil
}

// checkMachinePath proves a machine-owned path is safe to (re)generate: it
// is absent, or its marker file carries the generated header. Hand-written
// files without the marker refuse the apply.
func (a *CheckoutApplier) checkMachinePath(root, dir, markerFile string) error {
	if _, err := os.Stat(filepath.Join(root, dir)); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return fmt.Errorf("failed to inspect %s: %w", dir, err)
	}
	data, err := os.ReadFile(filepath.Join(root, markerFile))
	if err != nil {
		if os.IsNotExist(err) {
			return modgendomain.ErrTreeDirty
		}
		return fmt.Errorf("failed to inspect %s: %w", markerFile, err)
	}
	if !strings.Contains(string(data), generatedMarker) {
		return modgendomain.ErrTreeDirty
	}
	return nil
}

// writeProjectFiles materializes the project file map into dir. Paths ran
// the allowlist on the generation path, so a traversal here is defense in
// depth and aborts the apply.
func writeApplyFiles(dir string, files map[string]string) error {
	for path, content := range files {
		full := filepath.Join(dir, filepath.FromSlash(path))
		if !strings.HasPrefix(full, dir+string(os.PathSeparator)) {
			return fmt.Errorf("%w: %q", modgendomain.ErrPathNotAllowed, path)
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return fmt.Errorf("failed to create apply subdir: %w", err)
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			return fmt.Errorf("failed to write apply file: %w", err)
		}
	}
	return nil
}

// StageReplaceBackup moves an applied tree aside so a replace starts from
// a clean directory. It returns the backup path the rollback restores.
func StageReplaceBackup(moduleDir string) (string, error) {
	backup := moduleDir + ".modgen-backup"
	_ = os.RemoveAll(backup)
	if err := os.Rename(moduleDir, backup); err != nil {
		return "", err
	}
	return backup, nil
}

// RestoreReplaceBackup puts a staged backup back after a failed replace,
// removing any partial new tree first. An empty backup is a no-op.
func RestoreReplaceBackup(moduleDir, backup string) {
	if backup == "" {
		return
	}
	_ = os.RemoveAll(moduleDir)
	_ = os.Rename(backup, moduleDir)
}

// goWorkUseEntries parses the module entries of every go.work use block,
// single-line or multi-line. Matching is token-exact so a module never
// collides with a longer-prefixed sibling (forum vs forum2). A trailing
// comment after a single-line block is ignored.
func goWorkUseEntries(content string) []string {
	var entries []string
	inBlock := false
	for line := range strings.Lines(content) {
		trimmed := strings.TrimSpace(line)
		if !inBlock {
			rest, ok := strings.CutPrefix(trimmed, "use")
			if !ok {
				continue
			}
			rest = strings.TrimSpace(rest)
			if !strings.HasPrefix(rest, "(") {
				continue
			}
			after := rest[1:]
			if head, _, found := strings.Cut(after, ")"); found {
				entries = append(entries, strings.Fields(head)...)
				continue
			}
			if after != "" {
				entries = append(entries, strings.Fields(after)...)
			}
			inBlock = true
			continue
		}
		if trimmed == ")" {
			inBlock = false
			continue
		}
		entries = append(entries, strings.Fields(trimmed)...)
	}
	return entries
}

// hasGoWorkUseBlock reports whether content carries any use block at all.
func hasGoWorkUseBlock(content string) bool {
	for line := range strings.Lines(content) {
		trimmed := strings.TrimSpace(line)
		if trimmed == "use" || strings.HasPrefix(trimmed, "use (") || strings.HasPrefix(trimmed, "use\t(") {
			return true
		}
	}
	return false
}

// InsertGoWorkUse inserts ./modules/<name> into the go.work use block.
// Idempotent: a present entry is a no-op. A missing anchor fails closed.
func InsertGoWorkUse(content, name string) (string, error) {
	entry := "./modules/" + name
	if slices.Contains(goWorkUseEntries(content), entry) {
		return content, nil
	}
	lines := strings.Split(content, "\n")
	anchor := -1
	depth := 0
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if anchor < 0 {
			if !strings.HasPrefix(trimmed, goWorkAnchor) {
				continue
			}
			if strings.Contains(trimmed, ")") {
				return expandSingleLineUse(lines, i, trimmed, entry)
			}
			anchor = i
			depth = 1
			continue
		}
		if strings.Contains(trimmed, "(") {
			depth++
		}
		if trimmed == ")" {
			depth--
			if depth == 0 {
				out := make([]string, 0, len(lines)+1)
				out = append(out, lines[:i]...)
				out = append(out, "\t"+entry)
				out = append(out, lines[i:]...)
				return strings.Join(out, "\n"), nil
			}
		}
	}
	return "", fmt.Errorf("go.work use block not found")
}

// expandSingleLineUse rewrites a single-line use block (use (./a ./b)) into
// block form with the new entry appended. The closing paren is located
// from the right so trailing comments do not leak into the entries.
func expandSingleLineUse(lines []string, i int, trimmed, entry string) (string, error) {
	_, after, ok := strings.Cut(trimmed, "(")
	if !ok {
		return "", fmt.Errorf("go.work use block not found")
	}
	head, _, found := strings.Cut(after, ")")
	if !found {
		return "", fmt.Errorf("go.work use block not found")
	}
	inner := strings.TrimSpace(head)
	leading := lines[i][:len(lines[i])-len(strings.TrimLeft(lines[i], " \t"))]
	var rebuilt strings.Builder
	rebuilt.WriteString(leading + "use (\n")
	for part := range strings.FieldsSeq(inner) {
		rebuilt.WriteString(leading + "\t" + part + "\n")
	}
	rebuilt.WriteString(leading + "\t" + entry + "\n" + leading + ")")
	lines[i] = rebuilt.String()
	return strings.Join(lines, "\n"), nil
}

// AppendMakefileSubmodule extends the SUBMODULES line idempotently. A
// missing anchor fails closed.
func AppendMakefileSubmodule(content, name string) (string, error) {
	entry := "modules/" + name
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, makeSubmodulesAnchor) {
			continue
		}
		if slices.Contains(strings.Fields(trimmed), entry) {
			return content, nil
		}
		lines[i] = strings.TrimRight(line, " \t") + " " + entry
		return strings.Join(lines, "\n"), nil
	}
	return "", fmt.Errorf("SUBMODULES line not found in Makefile")
}

// RemoveGoWorkUse removes ./modules/<name> from the go.work use block.
// Idempotent: a missing entry is a no-op for registry/go.work desyncs. A
// missing use block fails closed.
func RemoveGoWorkUse(content, name string) (string, error) {
	entry := "./modules/" + name
	if !slices.Contains(goWorkUseEntries(content), entry) {
		if !hasGoWorkUseBlock(content) {
			return "", fmt.Errorf("go.work use block not found")
		}
		return content, nil
	}
	lines := strings.Split(content, "\n")
	anchor := -1
	depth := 0
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if anchor < 0 {
			if !strings.HasPrefix(trimmed, goWorkAnchor) {
				continue
			}
			if strings.Contains(trimmed, ")") {
				return expandSingleLineUseRemove(lines, i, trimmed, entry)
			}
			anchor = i
			depth = 1
			continue
		}
		if strings.Contains(trimmed, "(") {
			depth++
		}
		if trimmed == ")" {
			depth--
			if depth == 0 {
				break
			}
			continue
		}
		if depth >= 1 && trimmed == entry {
			out := make([]string, 0, len(lines)-1)
			out = append(out, lines[:i]...)
			out = append(out, lines[i+1:]...)
			return strings.Join(out, "\n"), nil
		}
	}
	if anchor < 0 {
		return "", fmt.Errorf("go.work use block not found")
	}
	return "", fmt.Errorf("go.work use block not found")
}

// expandSingleLineUseRemove rewrites a single-line use block minus the entry.
// An emptied block collapses back to the single-line form.
func expandSingleLineUseRemove(lines []string, i int, trimmed, entry string) (string, error) {
	_, after, ok := strings.Cut(trimmed, "(")
	if !ok {
		return "", fmt.Errorf("go.work use block not found")
	}
	head, _, found := strings.Cut(after, ")")
	if !found {
		return "", fmt.Errorf("go.work use block not found")
	}
	inner := strings.TrimSpace(head)
	leading := lines[i][:len(lines[i])-len(strings.TrimLeft(lines[i], " \t"))]
	kept := make([]string, 0)
	for part := range strings.FieldsSeq(inner) {
		if part != entry {
			kept = append(kept, part)
		}
	}
	if len(kept) == 0 {
		lines[i] = leading + "use ()"
		return strings.Join(lines, "\n"), nil
	}
	var rebuilt strings.Builder
	rebuilt.WriteString(leading + "use (\n")
	for _, part := range kept {
		rebuilt.WriteString(leading + "\t" + part + "\n")
	}
	rebuilt.WriteString(leading + ")")
	lines[i] = rebuilt.String()
	return strings.Join(lines, "\n"), nil
}

// RemoveMakefileSubmodule removes the modules/<name> token from the
// SUBMODULES line. Idempotent for registry/Makefile desyncs; a missing
// anchor fails closed.
func RemoveMakefileSubmodule(content, name string) (string, error) {
	entry := "modules/" + name
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		trimmed := strings.TrimSpace(line)
		if !strings.HasPrefix(trimmed, makeSubmodulesAnchor) {
			continue
		}
		fields := strings.Fields(line)
		kept := make([]string, 0, len(fields))
		for _, field := range fields {
			if field != entry {
				kept = append(kept, field)
			}
		}
		if len(kept) == len(fields) {
			return content, nil
		}
		lines[i] = strings.Join(kept, " ")
		return strings.Join(lines, "\n"), nil
	}
	return "", fmt.Errorf("SUBMODULES line not found in Makefile")
}

// customModuleAlias derives the Go import alias for an applied module. Names
// passed validation (lowercase alphanumerics, hyphen-free, no keywords), so
// the alias is the name itself.
func customModuleAlias(name string) string {
	return name
}

// customModuleWire renders one module's Wire line: the adopted database and
// logger when module.go declares WithDB, logger-only for older projects.
func customModuleWire(name, moduleGo string) string {
	alias := customModuleAlias(name)
	if strings.Contains(moduleGo, "WithDB(") {
		return "\t\t" + alias + ".New(\n\t\t\t" + alias + ".WithDB(core.DB, core.Dialect),\n\t\t\t" + alias + ".WithLogger(modules.NewLogger(core.Logger)),\n\t\t),"
	}
	return "\t\t" + alias + ".New(\n\t\t\t" + alias + ".WithLogger(modules.NewLogger(core.Logger)),\n\t\t),"
}

// RenderCustomEdition generates the machine-owned custom edition package
// from the applied registry. Every module adopts the shared database,
// dialect, and logger through its adoption options; the base blog
// composition wires first (the commerce decoration pattern).
func RenderCustomEdition(modules []string, moduleGo map[string]string) string {
	var b strings.Builder
	b.WriteString(generatedMarker + "\n")
	b.WriteString("// Regenerated on every apply from applied.json. Hand edits are lost.\n\n")
	b.WriteString("package custom\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"github.com/aristorinjuang/lesstruct/internal/app\"\n")
	b.WriteString("\t\"github.com/aristorinjuang/lesstruct/internal/modules\"\n")
	for _, name := range modules {
		b.WriteString("\t" + customModuleAlias(name) + " \"github.com/aristorinjuang/lesstruct/modules/" + name + "\"\n")
	}
	b.WriteString(")\n\n")
	b.WriteString("// Wrap returns the custom edition: the base composition plus every\n")
	b.WriteString("// applied module from applied.json. Modules adopt the shared database,\n")
	b.WriteString("// dialect, and logger through their adoption options.\n")
	b.WriteString("func Wrap(base app.Edition) app.Edition {\n")
	b.WriteString("\twire, mount := base.Wire, base.Mount\n")
	b.WriteString("\tbase.Name = \"custom\"\n")
	b.WriteString("\tbase.Wire = func(core *app.Core) error {\n")
	b.WriteString("\t\tif wire != nil {\n")
	b.WriteString("\t\t\tif err := wire(core); err != nil {\n")
	b.WriteString("\t\t\t\treturn err\n")
	b.WriteString("\t\t\t}\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t\tcore.Candidates = append(core.Candidates,\n")
	for _, name := range modules {
		b.WriteString(customModuleWire(name, moduleGo[name]) + "\n")
	}
	b.WriteString("\t\t)\n")
	b.WriteString("\t\treturn nil\n")
	b.WriteString("\t}\n")
	b.WriteString("\tbase.Mount = mount\n")
	b.WriteString("\treturn base\n")
	b.WriteString("}\n")
	return b.String()
}

// RenderCustomMain generates the machine-owned thin main for the custom
// binary, mirroring cmd/lesstruct-ecommerce/main.go.
func RenderCustomMain() string {
	var b strings.Builder
	b.WriteString(generatedMarker + "\n")
	b.WriteString("// The custom binary: the blog composition plus every applied module.\n")
	b.WriteString("// Rebuild after every apply to link newly staged modules.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"fmt\"\n")
	b.WriteString("\t\"os\"\n\n")
	b.WriteString("\t\"github.com/aristorinjuang/lesstruct/internal/app\"\n")
	b.WriteString("\tblogedition \"github.com/aristorinjuang/lesstruct/internal/editions/blog\"\n")
	b.WriteString("\tcustomedition \"github.com/aristorinjuang/lesstruct/internal/editions/custom\"\n")
	b.WriteString(")\n\n")
	b.WriteString("var version = \"dev\"\n\n")
	b.WriteString("func main() {\n")
	b.WriteString("\tif len(os.Args) > 1 && (os.Args[1] == \"--version\" || os.Args[1] == \"-version\") {\n")
	b.WriteString("\t\tfmt.Println(version)\n")
	b.WriteString("\t\treturn\n")
	b.WriteString("\t}\n")
	b.WriteString("\tapp.Run(customedition.Wrap(blogedition.Edition()))\n")
	b.WriteString("}\n")
	return b.String()
}

func (a *CheckoutApplier) snapshot(root string, paths []string) applySnapshot {
	snap := applySnapshot{files: make(map[string][]byte, len(paths))}
	for _, path := range paths {
		if data, err := os.ReadFile(filepath.Join(root, path)); err == nil {
			snap.files[path] = data
		}
	}
	return snap
}

func (a *CheckoutApplier) rollback(root string, snap applySnapshot) {
	for path, data := range snap.files {
		_ = os.WriteFile(filepath.Join(root, path), data, 0o644)
	}
	for _, dir := range snap.dirs {
		_ = os.RemoveAll(filepath.Join(root, dir))
	}
}

// runVerify executes one verification command under the caller's deadline
// and returns the step outcome.
func (a *CheckoutApplier) runVerify(ctx context.Context, root, name string, args []string, extraEnv []string) modgendomain.ApplyStep {
	output, err := a.runOrDefault()(ctx, root, applyEnv(extraEnv), a.goPathOrDefault(), args...)
	if err != nil {
		return modgendomain.NewApplyStep(name, false, false, verifyOutputTail(append(output, []byte("\nerror: "+err.Error())...)))
	}
	return modgendomain.NewApplyStep(name, true, false, "")
}

// verify runs the apply verification: module tests in the workspace, the
// isolated go.mod check (advisory: it needs the published kernel tag), and
// the custom-binary build. One deadline bounds all three steps.
// Verification failures keep the applied tree and report per-step outcomes.
func (a *CheckoutApplier) verify(ctx context.Context, root, name string) []modgendomain.ApplyStep {
	stepCtx, cancel := context.WithTimeout(ctx, a.timeoutOrDefault())
	defer cancel()
	steps := make([]modgendomain.ApplyStep, 0, 3)
	steps = append(steps, a.runVerify(stepCtx, root, "tests", []string{"test", "./modules/" + name + "/..."}, nil))
	steps = append(steps, a.runVerify(stepCtx, root, "isolated", []string{"test", "./modules/" + name + "/..."}, []string{"GOWORK=off"}))
	steps = append(steps, a.runVerify(stepCtx, root, "build", []string{"build", "./" + customMainDir}, nil))
	return steps
}

// moduleTreeDirty reports whether the applied module tree carries
// operator changes: any tracked-modified git entry (anything but untracked
// ??). Untracked-only content is recoverable from the staged copy and does
// not block removal. A git failure fails closed.
func (a *CheckoutApplier) moduleTreeDirty(ctx context.Context, root, name string) (bool, error) {
	output, err := a.runOrDefault()(ctx, root, applyEnv(nil), "git", "status", "--porcelain", "--", filepath.Join("modules", name))
	if err != nil {
		return false, err
	}
	for line := range strings.Lines(strings.TrimSpace(string(output))) {
		trimmed := strings.TrimSpace(line)
		if trimmed == "" {
			continue
		}
		if !strings.HasPrefix(trimmed, "??") {
			return true, nil
		}
	}
	return false, nil
}

// Unapply removes an applied module from the source checkout: the registry
// entry, the regenerated custom edition, and the module tree. The
// membership matrix decides: applied without a tree performs the
// registry/edition cleanup with ModuleDirRemoved false; anything the
// registry does not hold refuses with ErrNotApplied — hand-placed trees are
// never removed. Tracked operator edits inside the tree refuse with
// ErrTreeDirty. Verification runs the custom-binary build and keeps the
// removal on failure, reporting per-step outcomes.
func (a *CheckoutApplier) Unapply(ctx context.Context, name string, confirm bool) (modgendomain.UnapplyResult, error) {
	trimmed := strings.TrimSpace(name)
	if err := modgendomain.ValidateProjectName(trimmed); err != nil {
		return modgendomain.UnapplyResult{}, modgendomain.ErrNotApplied
	}
	if !confirm {
		return modgendomain.UnapplyResult{}, modgendomain.ErrConfirmationRequired
	}
	if _, err := exec.LookPath(a.goPathOrDefault()); err != nil {
		return modgendomain.UnapplyResult{}, modgendomain.ErrApplyUnavailable
	}
	root, err := a.checkoutRoot()
	if err != nil {
		return modgendomain.UnapplyResult{}, err
	}
	if err := a.checkCheckout(root); err != nil {
		return modgendomain.UnapplyResult{}, err
	}
	registered, err := a.readRegistry(root)
	if err != nil {
		return modgendomain.UnapplyResult{}, err
	}
	if !slices.Contains(registered, trimmed) {
		return modgendomain.UnapplyResult{}, modgendomain.ErrNotApplied
	}
	if err := a.checkClean(ctx, root); err != nil {
		return modgendomain.UnapplyResult{}, err
	}
	if err := a.checkMachinePath(root, customEditionDir, filepath.Join(customEditionDir, "custom.go")); err != nil {
		return modgendomain.UnapplyResult{}, err
	}
	moduleDir := filepath.Join(root, "modules", trimmed)
	_, statErr := os.Stat(moduleDir)
	dirGone := os.IsNotExist(statErr)
	if statErr != nil && !dirGone {
		return modgendomain.UnapplyResult{}, fmt.Errorf("%w: cannot inspect module tree: %v", modgendomain.ErrApplyFailed, statErr)
	}
	if !dirGone {
		dirty, err := a.moduleTreeDirty(ctx, root, trimmed)
		if err != nil {
			return modgendomain.UnapplyResult{}, fmt.Errorf("%w: cannot inspect module tree: %v", modgendomain.ErrTreeDirty, err)
		}
		if dirty {
			return modgendomain.UnapplyResult{}, modgendomain.ErrTreeDirty
		}
	}

	kept := make([]string, 0, len(registered))
	for _, entry := range registered {
		if entry != trimmed {
			kept = append(kept, entry)
		}
	}
	moduleSources := make(map[string]string, len(kept))
	for _, entry := range kept {
		data, err := os.ReadFile(filepath.Join(root, "modules", entry, "module.go"))
		if err != nil {
			return modgendomain.UnapplyResult{}, fmt.Errorf("%w: applied module %q has no readable tree; remove its stale registry entry before unapplying", modgendomain.ErrApplyFailed, entry)
		}
		moduleSources[entry] = string(data)
	}
	edition := RenderCustomEdition(kept, moduleSources)
	registry, err := json.MarshalIndent(kept, "", "  ")
	if err != nil {
		return modgendomain.UnapplyResult{}, fmt.Errorf("%w: cannot render registry: %v", modgendomain.ErrApplyFailed, err)
	}

	snap := a.snapshot(root, []string{
		"go.work",
		"Makefile",
		filepath.Join(customEditionDir, "custom.go"),
		appliedRegistryFile,
	})
	fail := func(err error) (modgendomain.UnapplyResult, error) {
		a.rollback(root, snap)
		return modgendomain.UnapplyResult{}, err
	}

	goWorkBytes, err := os.ReadFile(filepath.Join(root, "go.work"))
	if err != nil {
		return fail(fmt.Errorf("%w: cannot read go.work: %v", modgendomain.ErrApplyFailed, err))
	}
	updatedWork, err := RemoveGoWorkUse(string(goWorkBytes), trimmed)
	if err != nil {
		return fail(fmt.Errorf("%w: %v", modgendomain.ErrApplyFailed, err))
	}
	makefileBytes, err := os.ReadFile(filepath.Join(root, "Makefile"))
	if err != nil {
		return fail(fmt.Errorf("%w: cannot read Makefile: %v", modgendomain.ErrApplyFailed, err))
	}
	updatedMakefile, err := RemoveMakefileSubmodule(string(makefileBytes), trimmed)
	if err != nil {
		return fail(fmt.Errorf("%w: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, "go.work"), []byte(updatedWork), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write go.work: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, "Makefile"), []byte(updatedMakefile), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write Makefile: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, customEditionDir, "custom.go"), []byte(edition), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write custom edition: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, appliedRegistryFile), append(registry, '\n'), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write applied registry: %v", modgendomain.ErrApplyFailed, err))
	}
	// The tree goes last: everything before this point rolls back, nothing
	// after it can. A removal failure rolls back too — the tree was never
	// touched, so the pre-state restores completely.
	if !dirGone {
		if err := os.RemoveAll(moduleDir); err != nil {
			return fail(fmt.Errorf("%w: cannot remove module tree: %v", modgendomain.ErrApplyFailed, err))
		}
	}
	steps := []modgendomain.ApplyStep{a.runVerify(ctx, root, "build", []string{"build", "./" + customMainDir}, nil)}
	verified := steps[0].Passed
	return modgendomain.NewUnapplyResult(true, verified, steps, kept, !dirGone), nil
}
func (a *CheckoutApplier) Applied(_ context.Context) ([]string, error) {
	root, err := a.checkoutRoot()
	if err != nil {
		return []string{}, nil
	}
	modules, err := a.readRegistry(root)
	if err != nil {
		return nil, err
	}
	return modules, nil
}

// Apply stages one generated project into the source checkout: guard,
// writes with rollback, custom-edition regeneration, and verification.
// Verification failures keep the tree and report findings; write failures
// roll back. A colliding tree owned by the registry is replaced only with
// replace and confirm; hand-placed trees are never touched.
func (a *CheckoutApplier) Apply(ctx context.Context, project modgendomain.Project, replace, confirm bool) (modgendomain.ApplyResult, error) {
	if _, err := exec.LookPath(a.goPathOrDefault()); err != nil {
		return modgendomain.ApplyResult{}, modgendomain.ErrApplyUnavailable
	}
	if err := modgendomain.ValidateProjectName(project.Name); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	if err := modgendomain.ValidateProjectFiles(project.Files); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	root, err := a.checkoutRoot()
	if err != nil {
		return modgendomain.ApplyResult{}, err
	}
	if err := a.checkCheckout(root); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	moduleDir := filepath.Join(root, "modules", project.Name)
	if _, err := os.Stat(moduleDir); err == nil {
		registered, regErr := a.readRegistry(root)
		if regErr != nil {
			return modgendomain.ApplyResult{}, regErr
		}
		if !slices.Contains(registered, project.Name) || !replace || !confirm {
			return modgendomain.ApplyResult{}, modgendomain.ErrAlreadyApplied
		}
		// Replace destroys the applied tree: refuse when it carries
		// tracked operator edits, exactly like Unapply does.
		dirty, dirtyErr := a.moduleTreeDirty(ctx, root, project.Name)
		if dirtyErr != nil {
			return modgendomain.ApplyResult{}, fmt.Errorf("%w: cannot inspect module tree: %v", modgendomain.ErrTreeDirty, dirtyErr)
		}
		if dirty {
			return modgendomain.ApplyResult{}, modgendomain.ErrTreeDirty
		}
	}
	if err := a.checkClean(ctx, root); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	if err := a.checkMachinePath(root, customEditionDir, filepath.Join(customEditionDir, "custom.go")); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	if err := a.checkMachinePath(root, customMainDir, filepath.Join(customMainDir, "main.go")); err != nil {
		return modgendomain.ApplyResult{}, err
	}
	registered, err := a.readRegistry(root)
	if err != nil {
		return modgendomain.ApplyResult{}, err
	}
	goWork, err := os.ReadFile(filepath.Join(root, "go.work"))
	if err != nil {
		return modgendomain.ApplyResult{}, fmt.Errorf("%w: cannot read go.work: %v", modgendomain.ErrApplyFailed, err)
	}
	makefile, err := os.ReadFile(filepath.Join(root, "Makefile"))
	if err != nil {
		return modgendomain.ApplyResult{}, fmt.Errorf("%w: cannot read Makefile: %v", modgendomain.ErrApplyFailed, err)
	}

	snap := a.snapshot(root, []string{
		"go.work",
		"Makefile",
		filepath.Join(customEditionDir, "custom.go"),
		appliedRegistryFile,
	})
	backup := ""
	fail := func(err error) (modgendomain.ApplyResult, error) {
		a.rollback(root, snap)
		RestoreReplaceBackup(moduleDir, backup)
		return modgendomain.ApplyResult{}, err
	}

	updatedWork, err := InsertGoWorkUse(string(goWork), project.Name)
	if err != nil {
		return fail(fmt.Errorf("%w: %v", modgendomain.ErrApplyFailed, err))
	}
	updatedMakefile, err := AppendMakefileSubmodule(string(makefile), project.Name)
	if err != nil {
		return fail(fmt.Errorf("%w: %v", modgendomain.ErrApplyFailed, err))
	}
	moduleGo := project.Files["module.go"]
	modules := slices.Clone(registered)
	if !slices.Contains(modules, project.Name) {
		modules = append(modules, project.Name)
	}
	slices.Sort(modules)
	moduleSources := map[string]string{project.Name: moduleGo}
	for _, name := range registered {
		if name == project.Name {
			continue
		}
		data, err := os.ReadFile(filepath.Join(root, "modules", name, "module.go"))
		if err != nil {
			return fail(fmt.Errorf("%w: applied module %q has no readable tree; remove its stale registry entry before applying", modgendomain.ErrApplyFailed, name))
		}
		moduleSources[name] = string(data)
	}
	edition := RenderCustomEdition(modules, moduleSources)
	registry, err := json.MarshalIndent(modules, "", "  ")
	if err != nil {
		return fail(fmt.Errorf("%w: cannot render registry: %v", modgendomain.ErrApplyFailed, err))
	}

	if _, err := os.Stat(moduleDir); err == nil {
		var stageErr error
		backup, stageErr = StageReplaceBackup(moduleDir)
		if stageErr != nil {
			return fail(fmt.Errorf("%w: cannot stage replace backup: %v", modgendomain.ErrApplyFailed, stageErr))
		}
	}
	// The fresh or replacement tree is tracked before any byte lands: a
	// failure inside writeApplyFiles still removes the partial tree, and
	// on the replace path fail() restores the backup afterward.
	snap.dirs = append(snap.dirs, filepath.Join("modules", project.Name))
	if err := writeApplyFiles(moduleDir, project.Files); err != nil {
		return fail(fmt.Errorf("%w: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, "go.work"), []byte(updatedWork), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write go.work: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, "Makefile"), []byte(updatedMakefile), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write Makefile: %v", modgendomain.ErrApplyFailed, err))
	}
	if _, err := os.Stat(filepath.Join(root, customEditionDir)); os.IsNotExist(err) {
		snap.dirs = append(snap.dirs, customEditionDir)
	}
	if err := os.MkdirAll(filepath.Join(root, customEditionDir), 0o755); err != nil {
		return fail(fmt.Errorf("%w: cannot create custom edition: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, customEditionDir, "custom.go"), []byte(edition), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write custom edition: %v", modgendomain.ErrApplyFailed, err))
	}
	if err := os.WriteFile(filepath.Join(root, appliedRegistryFile), append(registry, '\n'), 0o644); err != nil {
		return fail(fmt.Errorf("%w: cannot write applied registry: %v", modgendomain.ErrApplyFailed, err))
	}
	// The replacement backup lives until every write succeeds: only the
	// verification outcome is left, and it never rolls back.
	if backup != "" {
		_ = os.RemoveAll(backup)
	}
	if _, err := os.Stat(filepath.Join(root, customMainDir)); os.IsNotExist(err) {
		if err := os.MkdirAll(filepath.Join(root, customMainDir), 0o755); err != nil {
			return fail(fmt.Errorf("%w: cannot create custom main: %v", modgendomain.ErrApplyFailed, err))
		}
		snap.dirs = append(snap.dirs, customMainDir)
		if err := os.WriteFile(filepath.Join(root, customMainDir, "main.go"), []byte(RenderCustomMain()), 0o644); err != nil {
			return fail(fmt.Errorf("%w: cannot write custom main: %v", modgendomain.ErrApplyFailed, err))
		}
	}

	steps := a.verify(ctx, root, project.Name)
	verified := true
	for _, step := range steps {
		if step.Name == "isolated" {
			continue
		}
		if !step.Passed {
			verified = false
		}
	}
	return modgendomain.NewApplyResult(true, verified, steps, modules, true), nil
}

// NewCheckoutApplier builds the checkout applier over root (the Lesstruct
// source checkout; "" means the server working directory). goPath names the
// Go toolchain ("" selects PATH lookup at call time); kernelVersion is
// recorded for future install metadata; timeout bounds verification ("" or
// non-positive selects the default); run executes verification commands
// (nil selects the real subprocess runner).
func NewCheckoutApplier(root, goPath, kernelVersion string, timeout time.Duration, run applyRunFunc) *CheckoutApplier {
	return &CheckoutApplier{
		root:          root,
		goPath:        goPath,
		kernelVersion: kernelVersion,
		timeout:       timeout,
		run:           run,
	}
}

var _ modgendomain.Applier = (*CheckoutApplier)(nil)
