package stylecheck_test

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/aristorinjuang/lesstruct/tools/stylecheck"
)

func TestChecker_CheckSource(t *testing.T) {
	tests := []struct {
		name    string
		source  string
		want    []string
		wantErr bool
	}{
		{
			name: "success - methods then constructor",
			source: `package fixture

type Service struct{}

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }
`,
		},
		{
			name: "success - non-New constructor closes the type",
			source: `package fixture

type Config struct{}

func (c *Config) Name() string { return "" }

func Load() (*Config, error) { return &Config{}, nil }
`,
		},
		{
			name: "success - witness beside its type",
			source: `package fixture

type Service struct{}

var _ any = (*Service)(nil)

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }
`,
		},
		{
			name: "success - helper precedes public declarations",
			source: `package fixture

func helper() {}

type Service struct{}

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }
`,
		},
		{
			name: "success - init is not a helper",
			source: `package fixture

type Service struct{}

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }

func init() {}
`,
		},
		{
			name: "success - grouped type declarations are skipped",
			source: `package fixture

type (
	A struct{}
	B struct{}
)

func (a *A) Run() {}
`,
		},
		{
			name: "success - enum const block sits between type and methods",
			source: `package fixture

type Status string

const (
	StatusOpen Status = "open"
)

func (s Status) String() string { return string(s) }

func ParseStatus(raw string) (Status, bool) { return Status(raw), true }
`,
		},
		{
			name: "success - first return value decides constructor",
			source: `package fixture

type service struct{}

func (s *service) Run() {}

func build() (string, *service) { return "", nil }
`,
		},
		{
			name: "success - generated files are skipped",
			source: `// Code generated by mockery. DO NOT EDIT.

package fixture

type Service struct{}

func NewService() *Service { return &Service{} }

func (s *Service) Run() {}
`,
		},
		{
			name: "error - constructor before methods",
			source: `package fixture

type Service struct{}

func NewService() *Service { return &Service{} }

func (s *Service) Run() {}
`,
			want: []string{"method Run of type Service appears after its constructor NewService"},
		},
		{
			name: "error - foreign declaration breaks the method block",
			source: `package fixture

type service struct{}

func helper() {}

func (s *service) Run() {}
`,
			want: []string{"helper breaks the method block of type service"},
		},
		{
			name: "error - helper after public declarations",
			source: `package fixture

type Service struct{}

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }

func helper() {}
`,
			want: []string{"package-level helper helper must precede public declarations"},
		},
		{
			name: "error - parse failure",
			source: `package fixture

func broken(`,
			wantErr: true,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			findings, err := stylecheck.NewChecker().CheckSource("fixture.go", []byte(tt.source))
			if tt.wantErr {
				require.Error(t, err)
				return
			}
			require.NoError(t, err)
			require.Len(t, findings, len(tt.want))
			for i, want := range tt.want {
				assert.Contains(t, findings[i].Message, want)
			}
		})
	}
}

func TestChecker_CheckDir(t *testing.T) {
	root := t.TempDir()
	files := map[string]string{
		"ok.go": `package fixture

type Service struct{}

func (s *Service) Run() {}

func NewService() *Service { return &Service{} }
`,
		"broken.go": `package fixture

type Repository struct{}

func NewRepository() *Repository { return &Repository{} }

func (r *Repository) Find() {}
`,
		"broken_test.go": `package fixture

type Repository struct{}

func NewRepository() *Repository { return &Repository{} }

func (r *Repository) Find() {}
`,
		"mocks/mock_repository.go": `// Code generated by mockery. DO NOT EDIT.

package mocks

type Repository struct{}

func NewRepository() *Repository { return &Repository{} }

func (r *Repository) Find() {}
`,
		"vendor/third_party.go": `package vendor

type Repository struct{}

func NewRepository() *Repository { return &Repository{} }

func (r *Repository) Find() {}
`,
	}
	for name, content := range files {
		path := filepath.Join(root, name)
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
	}

	findings, err := stylecheck.NewChecker().CheckDir(root)
	require.NoError(t, err)
	require.Len(t, findings, 1)
	assert.Contains(t, findings[0].Message, "method Find of type Repository")
}
